/* ORA PMS · Calendar rate matrix. Read-only daily rates, both calendar modes. */
(() => {
  'use strict';

  const page = document.getElementById('frontDeskCalendarPage') || document.getElementById('frontDeskCalendarMWPage');
  if (!page) return;
  const calendar = page.querySelector('#fdcCalendar');
  if (!calendar) return;

  // Compatible with the original MVC calendar as well as the enhanced headers.
  // Earlier 'changed files only' packages did not include the calendar view and
  // renderer changes, so requiring .ora-rates-date-trigger could silently make
  // a click do nothing. The selector below intentionally works with BOTH.
  const dateHeaderSelector = '.fdc-date-head .fdc-day[data-date], .fdcmw-fdc-date-head .fdcmw-fdc-day[data-date], .ora-rates-date-trigger[data-date]';
  // Prefer the URL generated by Razor (works under application subpaths).
  // Fallback allows the popup to initialize if an older calendar view lacks
  // data-rates-url, provided the rate controller has been deployed.
  const ratesUrl = page.dataset.ratesUrl || '/CalendarDateRates/ForDate';

  const isMonthView = page.id === 'frontDeskCalendarMWPage';
  const fallbackCurrency = page.dataset.currency || '';
  const hotelToday = page.dataset.hotelToday || '';
  const esc = value => String(value ?? '').replace(/[&<>"']/g, ch => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  }[ch]));
  const parseDate = input => {
    const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(input || ''));
    if (!match) return null;
    const date = new Date(+match[1], +match[2] - 1, +match[3]);
    return date.getFullYear() === +match[1] && date.getMonth() === +match[2] - 1 && date.getDate() === +match[3] ? date : null;
  };
  const dateIso = date => `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
  const shiftDay = (value, days) => {
    const date = parseDate(value);
    if (!date) return value;
    date.setDate(date.getDate() + days);
    return dateIso(date);
  };
  const formatDay = value => parseDate(value)?.toLocaleDateString('en-GB', {
    weekday: 'long', day: 'numeric', month: 'long', year: 'numeric'
  }) || value;
  const formatMoney = (value, currency) => {
    if (value === null || value === undefined || value === '' || !Number.isFinite(Number(value))) return '—';
    const unit = String(currency || fallbackCurrency || '').trim();
    const amount = Number(value);
    if (/^[A-Z]{3}$/.test(unit)) {
      try {
        return new Intl.NumberFormat('en-GB', { style: 'currency', currency: unit, minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(amount);
      } catch { /* fall back to property's currency label */ }
    }
    const number = amount.toLocaleString('en-GB', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
    return unit ? `${unit}${/^[£€$¥₹₨]/.test(unit) ? '' : ' '}${number}` : number;
  };

  const root = document.createElement('div');
  root.className = 'ora-rates-backdrop';
  root.setAttribute('aria-hidden', 'true');
  root.innerHTML = `
    <section class="ora-rates-panel" role="dialog" aria-modal="true" aria-labelledby="oraRatesTitle" tabindex="-1">
      <header class="ora-rates-hero">
        <h2 id="oraRatesTitle"><i class="fa-solid fa-table-cells-large" aria-hidden="true"></i> Daily room rates</h2>
        <div class="ora-rates-header-actions">
          <div class="ora-rates-day-picker" aria-label="Choose rate date">
            <button type="button" class="ora-rates-step" data-rates-prev title="Previous day" aria-label="Previous day"><i class="fa-solid fa-chevron-left" aria-hidden="true"></i></button>
            <strong class="ora-rates-date-caption" data-rates-date-caption>Choose a date</strong>
            <label class="ora-rates-date-input-wrap" title="Select rate date"><i class="fa-regular fa-calendar-days" aria-hidden="true"></i><input type="date" class="ora-rates-date-input" data-rates-date min="1900-01-01" max="2100-12-31" aria-label="Show rates for date" /></label>
            <button type="button" class="ora-rates-step" data-rates-next title="Next day" aria-label="Next day"><i class="fa-solid fa-chevron-right" aria-hidden="true"></i></button>
          </div>
          <button type="button" class="ora-rates-icon-btn" data-rates-close aria-label="Close rates popup" title="Close (Esc)"><i class="fa-solid fa-xmark" aria-hidden="true"></i></button>
        </div>
      </header>
      <div class="ora-rates-toolbar">
        <label class="ora-rates-search"><i class="fa-solid fa-magnifying-glass" aria-hidden="true"></i><input type="search" data-rates-search autocomplete="off" placeholder="Search categories or rate plans" aria-label="Search room category or rate plan" /></label>
        <span class="ora-rates-result-count" data-rates-results aria-live="polite"></span>
      </div>
      <div class="ora-rates-content" data-rates-content tabindex="0" aria-label="Scrollable matrix of rates by plan and category">
        <div class="ora-rates-loading" role="status"><span class="ora-rates-spinner"></span><strong>Loading rates...</strong></div>
      </div>
    </section>`;
  document.body.appendChild(root);

  const $ = selector => root.querySelector(selector);
  const dateInput = $('[data-rates-date]');
  const dateCaption = $('[data-rates-date-caption]');
  const content = $('[data-rates-content]');
  const search = $('[data-rates-search]');
  const resultCount = $('[data-rates-results]');
  let selected = '';
  let snapshot = null;
  let abortController = null;
  let requestSequence = 0;
  let openingTrigger = null;
  let previousBodyOverflow = '';

  function highlightHeader() {
    calendar.querySelectorAll('.ora-rates-selected-date').forEach(el => el.classList.remove('ora-rates-selected-date'));
    if (!root.classList.contains('ora-rates-open') || !selected) return;
    const key = isMonthView ? selected.slice(0, 7) : selected;
    for (const header of calendar.querySelectorAll(dateHeaderSelector)) {
      if ((isMonthView ? (header.dataset.date || '').slice(0, 7) : header.dataset.date) === key) {
        header.classList.add('ora-rates-selected-date');
      }
    }
  }

  function enhanceDateHeaders() {
    for (const header of calendar.querySelectorAll(dateHeaderSelector)) {
      // The headers are created again whenever the calendar is refreshed or
      // the date range changes. Keep them keyboard-accessible after each render.
      if (!header.classList.contains('ora-rates-date-trigger')) {
        header.classList.add('ora-rates-date-trigger');
      }
      if (header.getAttribute('role') !== 'button') header.setAttribute('role', 'button');
      if (header.tabIndex !== 0) header.tabIndex = 0;
      if (!header.hasAttribute('aria-label')) {
        header.setAttribute('aria-label', `View room rates for ${formatDay(header.dataset.date)}`);
      }
      if (!header.hasAttribute('title')) header.setAttribute('title', 'Click to view rates');
    }
    highlightHeader();
  }

  // Observe only added/removed nodes; modifying header classes cannot trigger
  // this observer recursively. No direct handlers are attached to dated cells.
  new MutationObserver(enhanceDateHeaders).observe(calendar, { childList: true, subtree: true });
  enhanceDateHeaders();

  function loading() {
    snapshot = null;
    resultCount.textContent = '';
    content.innerHTML = '<div class="ora-rates-loading" role="status"><span class="ora-rates-spinner"></span><strong>Loading rates...</strong></div>';
  }

  // Plan IDs differ across room categories. Match plans by their display name
  // so the same selling plan appears on one horizontal row for every category.
  // A second plan with the same name in a category receives its own row.
  function buildMatrix(categories) {
    const rows = new Map();
    categories.forEach((category, categoryIndex) => {
      const occurrences = new Map();
      for (const plan of Array.isArray(category.plans) ? category.plans : []) {
        const title = String(plan.planName || 'Unnamed rate plan').trim() || 'Unnamed rate plan';
        const normalized = title.replace(/\s+/g, ' ').toLocaleLowerCase();
        const ordinal = occurrences.get(normalized) || 0;
        occurrences.set(normalized, ordinal + 1);
        const key = `${normalized}\u0001${ordinal}`;
        if (!rows.has(key)) rows.set(key, { name: ordinal ? `${title} (${ordinal + 1})` : title, values: new Map(), parents: [] });
        const row = rows.get(key);
        row.values.set(categoryIndex, plan);
        if (plan.parentPlanName) row.parents.push(String(plan.parentPlanName));
      }
    });
    return [...rows.values()];
  }

  function rateCell(plan, category) {
    if (!plan) return '<td class="ora-rates-unmapped" title="Rate plan not mapped to this category">—</td>';
    const stopped = !!plan.isStopSell;
    const source = String(plan.source || '').toLowerCase();
    // Keep metadata in the tooltip instead of repeating badges in every cell.
    const detail = [
      stopped ? 'Stop sell: closed for sale' : 'Per room / night',
      plan.isDerived ? (plan.parentPlanName ? `Derived from ${plan.parentPlanName}` : 'Derived rate') : '',
      source.includes('rate-yield') ? 'Yield-adjusted rate' : source.includes('rate-manual') ? 'Manually adjusted rate' : ''
    ].filter(Boolean).join(' · ');
    const price = formatMoney(plan.rate, category.currency);
    return `<td class="ora-rates-rate-cell${stopped ? ' ora-rates-stopped' : ''}" title="${esc(detail)}">
      <span class="ora-rates-cell-price">${esc(price)}</span>
      ${stopped ? '<span class="ora-rates-stop-tag" title="Stop sell: closed for sale">Closed</span>' : ''}
    </td>`;
  }

  function render() {
    if (!snapshot || !root.classList.contains('ora-rates-open')) return;
    const allCategories = Array.isArray(snapshot.categories) ? snapshot.categories : [];
    const allRows = buildMatrix(allCategories);
    const query = search.value.trim().toLocaleLowerCase();
    const nameMatches = category => String(category.categoryName || '').toLocaleLowerCase().includes(query);
    const planMatches = row => `${row.name} ${row.parents.join(' ')}`.toLocaleLowerCase().includes(query);
    // Matching a category filters columns; otherwise match plan names to rows.
    const matchingIndexes = query ? allCategories.map((category, index) => nameMatches(category) ? index : -1).filter(index => index >= 0) : [];
    const categoryIndexes = matchingIndexes.length ? matchingIndexes : allCategories.map((_, index) => index);
    const rows = allRows.filter(row => {
      if (matchingIndexes.length) return categoryIndexes.some(index => row.values.has(index));
      return !query || planMatches(row);
    });
    const categories = categoryIndexes.map(index => allCategories[index]);
    resultCount.textContent = query
      ? `${categories.length} ${categories.length === 1 ? 'category' : 'categories'} · ${rows.length} ${rows.length === 1 ? 'plan' : 'plans'}` : '';

    if (!categories.length || !rows.length) {
      content.innerHTML = `<div class="ora-rates-empty"><i class="fa-solid fa-magnifying-glass" aria-hidden="true"></i><strong>${query ? 'No matching categories or rate plans' : 'No rate plans found for this date'}</strong><span>${query ? 'Try a different search term.' : 'No selling rate plans have been configured for the selected date.'}</span></div>`;
      return;
    }

    const columns = categories.map(category => {
      const name = category.categoryName || 'Room category';
      const available = category.availableRooms === null || category.availableRooms === undefined
        ? null : Number(category.availableRooms);
      const validAvailability = available !== null && Number.isFinite(available);
      const capacity = category.totalRooms == null ? '' : ` of ${category.totalRooms} rooms`;
      const status = !validAvailability ? 'unknown' : available <= 0 ? 'soldout' : 'available';
      const description = !validAvailability ? 'Availability unavailable' :
        available <= 0 ? '0 rooms available' : `${available} rooms available`;
      const badge = status === 'unknown' ? 'Availability n/a' : status === 'soldout' ? 'Sold out' : `${available} available`;
      return `<th scope="col" class="ora-rates-category-column" title="${esc(name + ' · ' + description + capacity)}">
        <span class="ora-rates-category-name">${esc(name)}</span>
        <span class="ora-rates-avail ora-rates-avail-${status}"><span class="ora-rates-avail-dot" aria-hidden="true"></span>${esc(badge)}</span>
      </th>`;
    }).join('');
    const body = rows.map(row => `<tr class="ora-rates-matrix-row">
        <th scope="row" class="ora-rates-plan-name" title="${esc(row.name)}"><span class="ora-rates-plan-text">${esc(row.name)}</span></th>
        ${categoryIndexes.map(index => rateCell(row.values.get(index), allCategories[index])).join('')}
      </tr>`).join('');

    content.innerHTML = `<div class="ora-rates-matrix-wrap"><table class="ora-rates-matrix" aria-label="Daily room rate matrix for ${esc(formatDay(selected))}">
      <thead><tr><th scope="col" class="ora-rates-corner"><span>RATE PLANS</span></th>${columns}</tr></thead>
      <tbody>${body}</tbody></table></div>`;
  }

  async function loadRates() {
    if (!selected) return;
    abortController?.abort();
    abortController = new AbortController();
    const thisRequest = ++requestSequence;
    loading();
    try {
      const url = new URL(ratesUrl, window.location.href);
      url.searchParams.set('date', selected);
      const response = await fetch(url.toString(), {
        method: 'GET', credentials: 'same-origin', signal: abortController.signal,
        headers: { 'Accept': 'application/json' }, cache: 'no-store'
      });
      if (response.status === 401) throw new Error('Your login session has expired. Please sign in again.');
      const result = await response.json();
      if (!response.ok || !result.ok) throw new Error(result.message || 'Could not load the rates for this date.');
      if (thisRequest !== requestSequence || !root.classList.contains('ora-rates-open')) return;
      snapshot = result;
      render();
    } catch (error) {
      if (error.name === 'AbortError' || thisRequest !== requestSequence) return;
      content.innerHTML = `<div class="ora-rates-empty ora-rates-error" role="alert"><i class="fa-solid fa-triangle-exclamation" aria-hidden="true"></i><strong>Rates unavailable</strong><span>${esc(error.message || 'Unable to retrieve rates.')}</span><button type="button" class="ora-rates-retry" data-rates-retry>Try again</button></div>`;
    }
  }

  function setDate(value) {
    const date = parseDate(value);
    if (!date || date.getFullYear() < 1900 || date.getFullYear() > 2100) return;
    selected = value;
    dateInput.value = value;
    dateCaption.textContent = formatDay(value);
    highlightHeader();
    loadRates();
  }

  function open(trigger) {
    if (!trigger?.dataset.date) return;
    openingTrigger = trigger;
    previousBodyOverflow = document.body.style.overflow;
    document.body.style.overflow = 'hidden';
    root.classList.add('ora-rates-open');
    root.setAttribute('aria-hidden', 'false');
    search.value = '';
    let date = trigger.dataset.date;
    // Month headers refer to a whole month; open today's day within that
    // month, or the first day, then allow selection of any other day.
    if (isMonthView && hotelToday.slice(0, 7) === date.slice(0, 7)) date = hotelToday;
    setDate(date);
    $('[data-rates-close]').focus();
  }

  function close() {
    abortController?.abort();
    requestSequence++;
    root.classList.remove('ora-rates-open');
    root.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = previousBodyOverflow;
    highlightHeader();
    if (openingTrigger?.isConnected) openingTrigger.focus({ preventScroll: true });
    openingTrigger = null;
  }

  function findDateHeader(event) {
    return event.target instanceof Element ? event.target.closest(dateHeaderSelector) : null;
  }
  // Capture before the calendar's own delegated handlers, so the header click
  // cannot be swallowed by another booking/cell interaction.
  calendar.addEventListener('click', event => {
    const trigger = findDateHeader(event);
    if (!trigger || !calendar.contains(trigger)) return;
    event.preventDefault();
    event.stopPropagation();
    open(trigger);
  }, true);
  calendar.addEventListener('keydown', event => {
    const trigger = findDateHeader(event);
    if (!trigger || !calendar.contains(trigger) || (event.key !== 'Enter' && event.key !== ' ')) return;
    event.preventDefault();
    event.stopPropagation();
    open(trigger);
  }, true);
  root.addEventListener('click', event => {
    if (event.target === root || event.target.closest('[data-rates-close]')) { close(); return; }
    if (event.target.closest('[data-rates-prev]')) { setDate(shiftDay(selected, -1)); return; }
    if (event.target.closest('[data-rates-next]')) { setDate(shiftDay(selected, 1)); return; }
    if (event.target.closest('[data-rates-retry]')) loadRates();
  });
  dateInput.addEventListener('change', () => {
    if (parseDate(dateInput.value)) setDate(dateInput.value);
    else dateInput.value = selected;
  });
  search.addEventListener('input', render);
  document.addEventListener('keydown', event => {
    if (!root.classList.contains('ora-rates-open')) return;
    if (event.key === 'Escape') { event.stopPropagation(); close(); return; }
    if (event.key === 'Tab') {
      const focusable = [...root.querySelectorAll('button:not(:disabled), input:not(:disabled)')]
        .filter(element => element.getClientRects().length > 0);
      if (!focusable.length) return;
      const first = focusable[0], last = focusable[focusable.length - 1];
      if (event.shiftKey && document.activeElement === first) { event.preventDefault(); last.focus(); }
      else if (!event.shiftKey && document.activeElement === last) { event.preventDefault(); first.focus(); }
    }
  }, true);
})();
